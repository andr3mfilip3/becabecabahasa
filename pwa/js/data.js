// ── Exercise builders ─────────────────────────────────────
//
// translation: { 'pt-PT': '...', 'id-ID': '...' }
//   — the meaning of the target word in the learner's language
//
// questionType:
//   'word'    → "How do you say '{translation}' in {lang}?"
//               options = target-language words (no translation needed)
//   'meaning' → "What does '{target}' mean?"
//               options = meanings in UI language  (optionsByLang required)
//
// For 'listening' the options are always meanings → optionsByLang required.

const mc = (target, ptTrans, idTrans, options) => ({
  type: 'multiple-choice', questionType: 'word',
  target,
  translation: { 'pt-PT': ptTrans, 'id-ID': idTrans },
  options,
});

const mcM = (target, ptTrans, idTrans, ptOpts, idOpts) => ({
  type: 'multiple-choice', questionType: 'meaning',
  target,
  translation: { 'pt-PT': ptTrans, 'id-ID': idTrans },
  optionsByLang: { 'pt-PT': ptOpts, 'id-ID': idOpts },
});

const mcI = (ptInstruction, idInstruction, options, answerIndex) => ({
  type: 'multiple-choice', questionType: 'instruction',
  instruction: { 'pt-PT': ptInstruction, 'id-ID': idInstruction },
  target: options[answerIndex],
  options,
  translation: {},
});

const ta = (target, ptTrans, idTrans) => ({
  type: 'type-answer',
  target,
  translation: { 'pt-PT': ptTrans, 'id-ID': idTrans },
});

const li = (target, ptTrans, idTrans, ptOpts, idOpts) => ({
  type: 'listening',
  target,
  translation: { 'pt-PT': ptTrans, 'id-ID': idTrans },
  optionsByLang: { 'pt-PT': ptOpts, 'id-ID': idOpts },
});

const sp = (target, ptTrans, idTrans) => ({
  type: 'speaking',
  target,
  translation: { 'pt-PT': ptTrans, 'id-ID': idTrans },
});

const wm = (sentence, answer, wordBank, ptTrans, idTrans) => ({
  type: 'word-match',
  sentence,
  answer,
  wordBank,
  target: answer,
  translation: { 'pt-PT': ptTrans, 'id-ID': idTrans },
});

const tut = (ptInstruction, idInstruction, exampleDesc, target, ptTrans, idTrans) => ({
  type: 'tutorial',
  instruction: { 'pt-PT': ptInstruction, 'id-ID': idInstruction },
  exampleDesc,
  target,
  translation: { 'pt-PT': ptTrans, 'id-ID': idTrans },
});

const tutRead = (ptInstruction, idInstruction, text) => ({
  type: 'tutorial-read',
  instruction: { 'pt-PT': ptInstruction, 'id-ID': idInstruction },
  text,
});

const tf = (sentence, answer, text) => ({
  type: 'true-false',
  sentence,
  answer,  // 'true' | 'false'
  text,
});

